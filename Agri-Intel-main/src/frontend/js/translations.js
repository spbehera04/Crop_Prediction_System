// Update all translatable elements
function updateTranslations() {
    const lang = currentLanguage;
    
    // Update elements with data-translate attribute
    document.querySelectorAll('[data-translate]').forEach(element => {
        const key = element.getAttribute('data-translate');
        if (translations[lang] && translations[lang][key]) {
            element.textContent = translations[lang][key];
        }
    });
    
    // Update placeholders
    document.querySelectorAll('[data-translate-placeholder]').forEach(element => {
        const key = element.getAttribute('data-translate-placeholder');
        if (translations[lang] && translations[lang][key]) {
            element.placeholder = translations[lang][key];
        }
    });
    
    // Update document title
    if (lang === 'hi') {
        document.title = 'AgriIntel - स्मार्ट फसल सिफारिश प्रणाली';
    } else if (lang === 'od') {
        document.title = 'AgriIntel - ସ୍ମାର୍ଟ ଫସଲ ସୁପାରିଶ ବ୍ୟବସ୍ଥା';
    } else if (lang === 'ta') {
        document.title = 'AgriIntel - ஸ்மார்ட் பயிர் பரிந்துரை அமைப்பு';
    } else {
        document.title = 'AgriIntel - Smart Crop Recommendation System';
    }
}
